; NDSCAN - rebuild one drive's Z3PLUS names from extensionless -NAME markers.
; BDOS searches only, staged table replacement, no image writes or ACL updates.
BDOS EQU 5
 ORG 100H
START:
 LD (OLDSP),SP
 LD SP,STACK
 LD A,(80H)
 CP 127
 JP NC,USAGE
 LD HL,81H
 LD B,A
 OR A
 JP Z,USAGE
TERM:INC HL
 DJNZ TERM
 LD (HL),0
 LD HL,81H
 CALL SPACE
 LD A,(HL)
 AND 0DFH
 SUB 'A'
 CP 16
 JP NC,USAGE
 LD (DRIVE),A
 INC A
 LD (DRONE),A
 INC HL
 LD A,(HL)
 CP ':'
 JP NZ,USAGE
 INC HL
 CALL SPACE
 OR A
 JR Z,OPTIONSOK
 CP '/'
 JP NZ,USAGE
 INC HL
 LD A,(HL)
 AND 0DFH
 CP 'Q'
 JP NZ,USAGE
 INC HL
 CALL SPACE
 OR A
 JP NZ,USAGE
 LD A,1
 LD (QUIET),A
OPTIONSOK:
 LD A,(DRIVE)
 LD E,A
 LD C,201
 CALL BDOS
 LD A,H
 CP 0A1H
 JP NZ,DENIED
 LD A,L
 CP 18H
 JP NZ,DENIED
 CALL ENVFIND
 JP C,BADENV
 ; Save caller state, then return disk errors instead of terminating early.
 LD C,25
 CALL BDOS
 LD (OLDDR),A
 LD C,32
 LD E,255
 CALL BDOS
 LD (OLDUSR),A
 LD DE,DMAPB
 LD C,49
 CALL BDOS
 LD (OLDDMA),HL
 LD DE,ERRPB
 LD C,49
 CALL BDOS
 LD (OLDERR),A
 LD A,1
 LD (SAVED),A
 LD C,45
 LD E,255
 CALL BDOS
 LD A,(DRIVE)
 LD E,A
 LD C,14
 CALL BDOS
 CP 255
 JP Z,DISKERR
 LD DE,DMABUF
 LD C,26
 CALL BDOS
 ; Preserve other drives byte-for-byte (including NDR passwords).
 LD HL,(NDRPTR)
 LD A,(CAPACITY)
 LD B,A
COPYOLD:
 LD A,(HL)
 OR A
 JR Z,OLDSKIP
 CP 17
 JP NC,BADENV
 LD C,A
 LD A,(DRONE)
 CP C
 JR Z,OLDSKIP
 PUSH BC
 PUSH HL
 CALL APPENDOLD
 POP HL
 POP BC
OLDSKIP:
 LD DE,18
 ADD HL,DE
 DJNZ COPYOLD
 XOR A
 LD (USER),A
SCANUSER:
 LD A,(USER)
 LD E,A
 LD C,32
 CALL BDOS
 XOR A
 LD (FOUND),A
 LD HL,FCBTEMPLATE
 LD DE,FCB
 LD BC,36
 LDIR
 LD C,17
 JR SEARCH
SEARCHNEXT:LD C,18
SEARCH:
 LD DE,FCB
 CALL BDOS
 CP 255
 JR NZ,ENTRY
 LD A,H
 OR A
 JP NZ,DISKERR
 JP USERDONE
ENTRY:
 AND 3
 LD L,A
 LD H,0
 ADD HL,HL
 ADD HL,HL
 ADD HL,HL
 ADD HL,HL
 ADD HL,HL
 LD DE,DMABUF+1
 ADD HL,DE
 ; Extension must be blank; -CATALOG.011 and other files are not markers.
 PUSH HL
 LD DE,8
 ADD HL,DE
 LD B,3
EXTCHK:
 LD A,(HL)
 AND 7FH
 CP ' '
 JP NZ,NOTMARKER
 INC HL
 DJNZ EXTCHK
 POP HL
 LD A,(HL)
 AND 7FH
 CP '-'
 JP NZ,SEARCHNEXT
 INC HL
 LD DE,CANDIDATE
 LD B,8
 LD A,' '
CLEARC:LD (DE),A
 INC DE
 DJNZ CLEARC
 LD DE,CANDIDATE
 LD B,7
 XOR A
 LD (PADDING),A
 LD (NAMELEN),A
CHARLOOP:
 LD A,(HL)
 AND 7FH
 CP ' '
 JR Z,PADCHAR
 PUSH AF
 LD A,(PADDING)
 OR A
 JP NZ,INVALIDPOP
 POP AF
 CALL VALID
 JP C,BADMARK
 LD (DE),A
 LD A,(NAMELEN)
 INC A
 LD (NAMELEN),A
 JR CHARSTEP
PADCHAR:
 LD A,1
 LD (PADDING),A
CHARSTEP:
 INC HL
 INC DE
 DJNZ CHARLOOP
 LD A,(NAMELEN)
 OR A
 JP Z,BADMARK
 LD A,(FOUND)
 OR A
 JR NZ,COMPAREUSER
 LD HL,CANDIDATE
 LD DE,USERNAME
 LD BC,8
 LDIR
 LD A,1
 LD (FOUND),A
 JP SEARCHNEXT
COMPAREUSER:
 LD HL,CANDIDATE
 LD DE,USERNAME
 LD B,8
SAMEUSER:
 LD A,(DE)
 CP (HL)
 JP NZ,MULTIPLE
 INC HL
 INC DE
 DJNZ SAMEUSER
 JP SEARCHNEXT
NOTMARKER:
 POP HL
 JP SEARCHNEXT
INVALIDPOP:
 POP AF
 JP BADMARK
USERDONE:
 LD A,(FOUND)
 OR A
 JR Z,NEXTUSER
 CALL CHECKDUP
 JP C,DUPLICATE
 LD A,(COUNT)
 LD B,A
 LD A,(CAPACITY)
 CP B
 JP Z,FULL
 LD HL,(NEXTENTRY)
 LD A,(DRONE)
 LD (HL),A
 INC HL
 LD A,(USER)
 LD (HL),A
 INC HL
 EX DE,HL
 LD HL,USERNAME
 LD BC,8
 LDIR
 LD B,8
 LD A,' '
PASSWORD:LD (DE),A
 INC DE
 DJNZ PASSWORD
 LD (NEXTENTRY),DE
 LD A,(COUNT)
 INC A
 LD (COUNT),A
NEXTUSER:
 LD A,(USER)
 INC A
 LD (USER),A
 CP 16
 JP C,SCANUSER
 ; Commit only after every user area and every marker has been validated.
 LD HL,STAGE
 LD DE,(NDRPTR)
 LD BC,(NDRBYTES)
 LDIR
 LD A,(QUIET)
 OR A
 JP NZ,EXIT
 LD A,(DRIVE)
 ADD A,'A'
 LD (MSGDR),A
 LD DE,OKMSG
 CALL PRINT
 JP EXIT
APPENDOLD:
 LD DE,(NEXTENTRY)
 LD BC,18
 LDIR
 LD (NEXTENTRY),DE
 LD A,(COUNT)
 INC A
 LD (COUNT),A
 RET
CHECKDUP:
 LD A,(COUNT)
 OR A
 RET Z
 LD B,A
 LD HL,STAGE
DUPLOOP:
 PUSH BC
 PUSH HL
 INC HL
 INC HL
 LD DE,USERNAME
 LD B,8
DUPCHAR:
 LD A,(DE)
 CP (HL)
 JR NZ,DIFFERENT
 INC DE
 INC HL
 DJNZ DUPCHAR
 POP HL
 POP BC
 SCF
 RET
DIFFERENT:
 POP HL
 POP BC
 LD DE,18
 ADD HL,DE
 DJNZ DUPLOOP
 OR A
 RET
; Find the resident class-80 Z3ENV using signature and its self pointer.
; ENV+15h = NDR address, +17h = number of 18-byte entries.
ENVFIND:
 LD HL,8000H
ENVLOOP:
 LD A,(HL)
 CP 0C3H
 JR NZ,ENVNEXT
 PUSH HL
 LD DE,3
 ADD HL,DE
 LD DE,SIGNATURE
 LD B,6
SIGLOOP:
 LD A,(DE)
 CP (HL)
 JR NZ,SIGNO
 INC HL
 INC DE
 DJNZ SIGLOOP
 POP HL
 PUSH HL
 LD DE,1BH
 ADD HL,DE
 LD E,(HL)
 INC HL
 LD D,(HL)
 POP HL
 LD A,L
 CP E
 JR NZ,ENVNEXT
 LD A,H
 CP D
 JR NZ,ENVNEXT
 LD DE,15H
 ADD HL,DE
 LD E,(HL)
 INC HL
 LD D,(HL)
 INC HL
 LD A,(HL)
 OR A
 JR Z,ENVFAIL
 CP 65
 JR NC,ENVFAIL
 LD (CAPACITY),A
 LD (NDRPTR),DE
 LD HL,0
 LD DE,18
 LD B,A
BYTESLOOP:ADD HL,DE
 DJNZ BYTESLOOP
 LD (NDRBYTES),HL
 LD DE,(NDRPTR)
 LD A,D
 CP 80H
 JR C,ENVFAIL
 ADD HL,DE
 JR C,ENVFAIL
 LD A,H
 CP 0FFH
 JR NC,ENVFAIL
 LD HL,STAGE
 LD (NEXTENTRY),HL
 OR A
 RET
SIGNO:POP HL
ENVNEXT:
 INC HL
 LD A,H
 CP 0FFH
 JR C,ENVLOOP
ENVFAIL:SCF
 RET
SPACE:
 LD A,(HL)
 CP ' '
 RET NZ
 INC HL
 JR SPACE
VALID:
 CP '0'
 JR C,INVALID
 CP '9'+1
 JR C,VALIDOK
 CP 'A'
 JR C,INVALID
 CP 'Z'+1
 JR C,VALIDOK
 CP '_'
 JR NZ,INVALID
VALIDOK:OR A
 RET
INVALID:SCF
 RET
USAGE:LD DE,USEMSG
 JR ERROR
DENIED:LD DE,DENYMSG
 JR ERROR
BADENV:LD DE,ENVMSG
 JR ERROR
DISKERR:LD DE,DISKMSG
 JR ERROR
BADMARK:LD DE,MARKMSG
 JR ERROR
MULTIPLE:LD DE,MULTIMSG
 JR ERROR
DUPLICATE:LD DE,DUPMSG
 JR ERROR
FULL:LD DE,FULLMSG
ERROR:
 LD A,1
 LD (RESULT),A
 CALL PRINT
EXIT:
 LD A,(SAVED)
 OR A
 JR Z,RETURN
 LD A,(OLDDR)
 LD E,A
 LD C,14
 CALL BDOS
 LD A,(OLDUSR)
 LD E,A
 LD C,32
 CALL BDOS
 LD DE,(OLDDMA)
 LD C,26
 CALL BDOS
 LD A,(OLDERR)
 LD E,A
 LD C,45
 CALL BDOS
RETURN:
 LD DE,0
 LD A,(RESULT)
 OR A
 JR Z,STATUS
 LD DE,0FF01H
STATUS:
 LD C,108
 CALL BDOS
 LD SP,(OLDSP)
 RET
PRINT:LD C,9
 JP BDOS
OLDSP:DW 0
OLDDMA:DW 80H
OLDDR:DB 0
OLDUSR:DB 0
OLDERR:DB 0
SAVED:DB 0
RESULT:DB 0
QUIET:DB 0
DRIVE:DB 0
DRONE:DB 1
CAPACITY:DB 0
NDRPTR:DW 0
NDRBYTES:DW 0
NEXTENTRY:DW STAGE
COUNT:DB 0
USER:DB 0
FOUND:DB 0
NAMELEN:DB 0
PADDING:DB 0
CANDIDATE:DS 8,0
USERNAME:DS 8,0
SIGNATURE:DB 'Z3ENV',80H
DMAPB:DB 3CH,0,0,0
ERRPB:DB 4BH,0,0,0
FCBTEMPLATE:DB 0,'-???????   '
 DS 24,0
FCB:DS 36,0
DMABUF:DS 128,0
STAGE:DS 1152,0
USEMSG:DB 'Usage: NDSCAN drive: [/Q]',13,10,'$'
DENYMSG:DB 'NDSCAN requires an updated BYE and read access to every user area.',13,10
 DB 'Names unchanged.',13,10,'$'
ENVMSG:DB 'Unsupported Z3PLUS named-directory table. Names unchanged.',13,10,'$'
DISKMSG:DB 'Directory scan failed. Names unchanged.',13,10,'$'
MARKMSG:DB 'Invalid -NAME marker (use 1-7 letters/digits/underscores). Names unchanged.',13,10,'$'
MULTIMSG:DB 'Multiple -NAME markers in one user area. Names unchanged.',13,10,'$'
DUPMSG:DB 'Duplicate directory name. Names unchanged.',13,10,'$'
FULLMSG:DB 'Named-directory table full. Names unchanged.',13,10,'$'
OKMSG:DB 'NDSCAN '
MSGDR:DB 'P: names updated.',13,10,'$'
 DS 256,0
STACK:
 END
