; YSEND.COM reads one archive file with CP/M 3 BDOS for a YMODEM download.
BDOS	EQU	0005H
DFCB	EQU	005CH
SENDP	EQU	63
DATAP	EQU	64

	ORG	0100H
	LD	A,(DFCB)
	CP	10		; J:
	JR	Z,FILE
	CP	16		; P:
	JP	NZ,USAGE
FILE:	LD	A,(DFCB+1)
	CP	' '
	JP	Z,USAGE
	LD	HL,DFCB
	LD	DE,FCB
	LD	BC,12
	LDIR
	LD	HL,FCB+1
	LD	B,11
NAME:	LD	A,(HL)
	CP	'?'
	JP	Z,USAGE
	INC	HL
	DJNZ	NAME

	LD	A,0FFH		; CP/M 3 returns last-record byte count in CR.
	LD	(FCB+32),A
	LD	DE,FCB
	LD	C,15
	CALL	BDOS
	CP	0FFH
	JR	Z,FAIL
	LD	A,0FFH
	OUT	(SENDP),A
	LD	HL,FCB+1
	LD	B,11
HEADER:	LD	A,(HL)
	AND	7FH
	OUT	(SENDP),A
	INC	HL
	DJNZ	HEADER
	LD	A,(FCB+32)
	OUT	(SENDP),A
	XOR	A
	LD	(FCB+32),A
	LD	DE,BUFFER
	LD	C,26
	CALL	BDOS

NEXT:	LD	DE,FCB
	LD	C,20
	CALL	BDOS
	CP	1
	JR	Z,TRANSMIT
	OR	A
	JR	NZ,ABORT
	LD	HL,BUFFER
	LD	B,128
RECORD:	LD	A,(HL)
	OUT	(DATAP),A
	INC	HL
	DJNZ	RECORD
	IN	A,(SENDP)
	OR	A
	JR	Z,NEXT
ABORT:	LD	A,0FDH
	OUT	(SENDP),A
	JR	FAIL
TRANSMIT:
	LD	A,0FEH
	OUT	(SENDP),A
	IN	A,(SENDP)
	OR	A
	JR	NZ,FAIL
	LD	DE,OKMSG
	JR	PRINT
USAGE:	LD	DE,USEMSG
	JR	PRINT
FAIL:	LD	DE,FAILMSG
PRINT:	LD	C,9
	CALL	BDOS
	LD	DE,0080H
	LD	C,26
	CALL	BDOS
	RET

USEMSG:	DB	'Usage: YSEND J:filename.ext or YSEND P:filename.ext',13,10,'$'
FAILMSG:DB	13,10,'YMODEM download failed.',13,10,'$'
OKMSG:	DB	13,10,'YMODEM download complete.',13,10,'$'
FCB:	DS	36,0
BUFFER:	DS	128
	END
