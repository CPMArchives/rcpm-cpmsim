; Drive-aware MOUNT for RCP/M CP/M 3; successful swaps chain to NDSCAN.
BDOS EQU 5
MOUNTP EQU 60
 ORG 100H
START:
 LD (OLDSP),SP
 LD SP,STACK
 LD A,9
 LD (DRIVE),A
 LD A,(80H)
 CP 127
 JP NC,USAGE
 LD B,A
 LD HL,81H
 OR A
 JP Z,USAGE
UPCASE:
 LD A,(HL)
 CP 'a'
 JR C,UPNEXT
 CP 'z'+1
 JR NC,UPNEXT
 SUB 32
 LD (HL),A
UPNEXT:
 INC HL
 DJNZ UPCASE
 LD (HL),0
 LD HL,81H
 CALL SPACE
 PUSH HL
 INC HL
 LD A,(HL)
 CP ':'
 POP HL
 JR NZ,ARG
 LD A,(HL)
 CP 'J'
 JR Z,DRJ
 CP 'P'
 JP NZ,USAGE
 LD A,15
 JR SETDR
DRJ:LD A,9
SETDR:LD (DRIVE),A
 LD A,1
 LD (EXPLICIT),A
 INC HL
 INC HL
 CALL SPACE
ARG:
 LD A,(HL)
 OR A
 JP Z,USAGE
 CP '/'
 JR NZ,NAME
 INC HL
 LD DE,LOPT
 CALL SAME
 JP Z,LIST
 LD DE,DOPT
 CALL SAME
 JP NZ,USAGE
 LD A,1
 LD (DEFAULT),A
 JR REQUEST
NAME:
 LD DE,VNAME
 LD B,8
NAMENX:
 LD A,(HL)
 OR A
 JR Z,NAMEEND
 CP ' '
 JR Z,NAMEEND
 CALL VALID
 JP C,USAGE
 LD (DE),A
 INC DE
 INC HL
 DJNZ NAMENX
 LD A,(HL)
 OR A
 JR Z,NAMEEND
 CP ' '
 JP NZ,USAGE
NAMEEND:
 XOR A
 LD (DE),A
 CALL SPACE
 OR A
 JP NZ,USAGE
REQUEST:
 CALL CAPABILITY
 JP NZ,UPDATE
 ; Refuse a swap if the independently installed follow-up utility is missing.
 CALL CHECKSCAN
 JP NZ,NOSCAN
 LD C,48
 LD E,0
 CALL BDOS
 OR A
 JP NZ,FLUSHERR
 LD A,(DEFAULT)
 OR A
 JR Z,NAMED
 LD A,(DRIVE)
 CP 15
 LD A,0F9H
 JR NZ,SENDDEFAULT
 INC A
SENDDEFAULT:
 OUT (MOUNTP),A
 JR STATUS
NAMED:
 LD A,(EXPLICIT)
 OR A
 LD A,0F8H
 JR Z,BEGINNAME
 LD A,(DRIVE)
 CP 15
 LD A,0FFH
 JR NZ,BEGINNAME
 LD A,0FDH
BEGINNAME:
 OUT (MOUNTP),A
 LD HL,VNAME
SENDNAME:
 LD A,(HL)
 OUT (MOUNTP),A
 OR A
 JR Z,STATUS
 INC HL
 JR SENDNAME
STATUS:
 IN A,(MOUNTP)
 CP 4
 JP Z,AMBIGUOUS
 CP 3
 JP Z,GEOMETRY
 LD B,A
 LD A,(EXPLICIT)
 OR A
 JR NZ,OLDSTATUS
 LD A,(DEFAULT)
 OR A
 JR NZ,OLDSTATUS
 LD A,B
 SUB 10H
 CP 2
 JP NC,FAILED
 OR A
 LD A,9
 JR Z,AUTODRIVE
 LD A,15
AUTODRIVE:
 LD (DRIVE),A
 JR SUCCESS
OLDSTATUS:
 LD A,B
 OR A
 JP NZ,FAILED
SUCCESS:
 ; Reset only the replaced drive, log it in, restore the previous selection.
 LD C,25
 CALL BDOS
 LD (OLDSEL),A
 LD A,(DRIVE)
 CP 15
 LD DE,0200H
 JR NZ,RESET
 LD DE,8000H
RESET:
 LD C,37
 CALL BDOS
 LD A,(DRIVE)
 LD E,A
 LD C,14
 CALL BDOS
 LD A,(OLDSEL)
 LD E,A
 LD C,14
 CALL BDOS
 LD A,(DRIVE)
 ADD A,'A'
 LD (OKDR),A
 LD (CHAINDR),A
 LD DE,VOLMSG
 CALL PRINT
 LD A,(DEFAULT)
 OR A
 JR Z,SHOWVNAME
 LD DE,DEFMSG
 CALL PRINT
 JR SHOWDRIVE
SHOWVNAME:
 LD HL,VNAME
SHOWCHAR:
 LD A,(HL)
 OR A
 JR Z,SHOWDRIVE
 PUSH HL
 LD E,A
 LD C,2
 CALL BDOS
 POP HL
 INC HL
 JR SHOWCHAR
SHOWDRIVE:
 LD DE,OKMSG
 CALL PRINT
 LD HL,CHAIN
 LD DE,80H
 LD BC,16
 LDIR
 LD C,47
 LD E,255
 CALL BDOS
 RET
LIST:
 CALL CAPABILITY
 JP NZ,UPDATE
 LD A,(EXPLICIT)
 OR A
 JR NZ,LISTSINGLE
 LD A,9
 LD (DRIVE),A
 CALL LISTONE
 LD DE,BLANK
 CALL PRINT
 LD A,15
 LD (DRIVE),A
LISTSINGLE:
 CALL LISTONE
 JP EXITOK
LISTONE:
 LD A,(DRIVE)
 CP 15
 LD A,0FEH
 JR NZ,LISTGO
 LD A,0FCH
LISTGO:
 OUT (MOUNTP),A
LISTNX:
 IN A,(MOUNTP)
 OR A
 RET Z
 LD E,A
 LD C,2
 CALL BDOS
 JR LISTNX
CHECKSCAN:
 LD C,32
 LD E,255
 CALL BDOS
 PUSH AF
 LD C,32
 LD E,0
 CALL BDOS
 LD DE,SCANFCB
 LD C,15
 CALL BDOS
 CP 255
 JR Z,SCANNONE
 LD DE,SCANFCB
 LD C,16
 CALL BDOS
 XOR A
 JR SCANSET
SCANNONE:LD A,1
SCANSET:LD (SCANSTATUS),A
 POP AF
 LD E,A
 LD C,32
 CALL BDOS
 LD A,(SCANSTATUS)
 OR A
 RET
CAPABILITY:
 LD A,0F7H
 OUT (MOUNTP),A
 IN A,(MOUNTP)
 CP 0A3H
 RET
SPACE:
 LD A,(HL)
 CP ' '
 RET NZ
 INC HL
 JR SPACE
; Compare a complete option with trailing spaces allowed; preserve HL.
SAME:
 PUSH HL
SAMENX:
 LD A,(DE)
 OR A
 JR Z,SAMETAIL
 CP (HL)
 JR NZ,SAMERET
 INC DE
 INC HL
 JR SAMENX
SAMETAIL:
 CALL SPACE
 OR A
SAMERET:
 POP HL
 RET
VALID:
 CP '0'
 JR C,INVALID
 CP '9'+1
 JR C,VALIDOK
 CP 'A'
 JR C,INVALID
 CP 'Z'+1
 JR C,VALIDOK
 CP '_'
 JR NZ,INVALID
VALIDOK:OR A
 RET
INVALID:SCF
 RET
USAGE:LD DE,USEMSG
 JR ERROR
UPDATE:LD DE,UPDMSG
 JR ERROR
NOSCAN:LD DE,SCANMSG
 JR ERROR
FLUSHERR:LD DE,FLUSHMSG
 JR ERROR
GEOMETRY:LD DE,GEOMSG
 JR ERROR
AMBIGUOUS:LD DE,AMBMSG
 JR ERROR
FAILED:LD DE,FAILMSG
ERROR:
 CALL PRINT
 LD DE,0FF01H
 JR EXIT
EXITOK:LD DE,0
EXIT:
 LD C,108
 CALL BDOS
 LD SP,(OLDSP)
 RET
PRINT:LD C,9
 JP BDOS
OLDSP:DW 0
OLDSEL:DB 0
SCANSTATUS:DB 0
DRIVE:DB 9
DEFAULT:DB 0
EXPLICIT:DB 0
VNAME:DS 9,0
LOPT:DB 'L',0
DOPT:DB 'DEFAULT',0
CHAIN:DB 'A0:NDSCAN '
CHAINDR:DB 'J: /Q',0
SCANFCB:DB 1,'NDSCAN  COM'
 DS 24,0
USEMSG:DB 'MOUNT [J:|P:] name | /L | /DEFAULT',13,10,'$'
UPDMSG:DB 'Mount interface unavailable; update the RCP/M runtime.',13,10,'$'
SCANMSG:DB 'A0:NDSCAN.COM missing. Mounted image unchanged.',13,10,'$'
FLUSHMSG:DB 'Flush failed. Mounted image unchanged.',13,10,'$'
GEOMSG:DB 'Wrong image geometry: J: requires 4177920 bytes; P: 536870912.',13,10
 DB 'Mounted image unchanged.',13,10,'$'
FAILMSG:DB 'Volume unavailable. Mounted image unchanged.',13,10,'$'
VOLMSG:DB 'Volume $'
DEFMSG:DB '<default>$'
BLANK:DB 13,10,'$'
AMBMSG:DB 'Ambiguous volume name; use MOUNT J: name or MOUNT P: name.',13,10,'$'
OKMSG:DB ' mounted on '
OKDR:DB 'J:',13,10,'$'
 DS 192,0
STACK:
 END
